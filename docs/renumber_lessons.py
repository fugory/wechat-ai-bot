s = io.open(P, encoding="utf-8").read()

pairs = [
    ("## 一、与微信交互的硬坑", "## A. 与微信交互的硬坑"),
    ("## 二、硬性红线", "## B. 硬性红线（本项目）"),
    ("## 三、当前架构的关键事实（免得重新发现）", "## C. 架构关键事实（免得重新发现）"),
    ("## 四、切会话与坐标（UIA 相关）", "## D. 切会话与坐标（UIA 相关）"),
    ("## 五、表情与记忆（产品级约束）", "## E. 表情与记忆（产品级约束）"),
    ("## 六、卡死与节流（2026-10-26/27）", "## F. 卡死与节流"),
    ("## 十、切会话：不要猜行号，要按名字点", "## 10. 切会话：不要猜行号，要按名字点"),
    ("## 十一、坐标不要算，要去问 UIA", "## 11. 坐标不要算，要去问 UIA"),
    ("## 十二、不要改微信窗口的样式（WS_CAPTION）", "## 12. 不要改微信窗口的样式（WS_CAPTION）"),
    ("## 十三、坐标别信缓存：同一个窗口，两处读到两种尺寸",
     "## 13. 坐标别信缓存：同一个窗口，两处读到两种尺寸"),
    ('## 十四、表情发送：微信 4.x 堵死了所有"本地文件"入口',
     '## 14. 表情发送：微信 4.x 堵死了所有"本地文件"入口'),
]

